// 简单确定性哈希：对 "YYYY-MM-DD" 字符串逐字符累积取模，保证同一天全球同题
function hashDateText(dateText) {
  const text = String(dateText || "");
  let hash = 0;
  for (let index = 0; index < text.length; index += 1) {
    hash = (hash * 31 + text.charCodeAt(index)) % 1000003;
  }
  return hash;
}

function questionForDate(dateText) {
  const index = hashDateText(dateText) % QUESTIONS.length;
  const question = QUESTIONS[index];
  return { id: question.id, text: question.text };
}

